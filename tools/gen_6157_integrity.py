#!/usr/bin/env python3
"""Generate/check the unified deployed-asset integrity manifest for 6.1.x.

The manifest contains only repository-relative asset paths and SHA-256 values.
It never executes native assets and is independent of device model or runtime
kernel addresses.  The runner selects rows by its exact P6157 profile.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "main/app/assets"
OUTPUT = ASSETS / "6157-integrity.tsv"
CGA_SHARED = (
    "g264/ko_slide_patch",
    "ksu6157-g264/ksud",
    "ksu6157-g264/sigparam",
    "su-g264/setup_su_app.sh",
    "su-g264/su_lkm",
    "su-g264/su_optional.sh",
    "su-g264/su_overlay_helper",
)
G264_LEGACY = (
    "ksu6157-g264/ksu_prepare",
    "ksu6157-g264/ksu-loader",
    "ksu6157-g264/ksu-syms.txt",
)


def digest(path: Path) -> str:
    data = path.read_bytes()
    if not data:
        raise ValueError(f"empty asset: {path}")
    return hashlib.sha256(data).hexdigest()


def generate() -> tuple[str, dict[str, int]]:
    table = json.loads((ROOT / "tools/kernel_profiles.json").read_text(encoding="utf-8"))
    m6 = json.loads((ROOT / "binary-sources/61157-g264/m6-provenance.json").read_text(
        encoding="utf-8"))
    rows: list[tuple[str, str, str]] = []
    counts: dict[str, int] = {}
    for profile in table["profiles_61x"]:
        if profile["id"] == "g19a":
            continue
        pid = "6157" if profile["id"] == "g7d" else profile["id"]
        payload_dir = profile["payload_dir"]
        paths = [f"{payload_dir}/exploit-android-key-ptr", f"{payload_dir}/pc98260-su"]
        if profile["cga_base"]:
            syms = (profile["cga_base"].replace("ksm-", "syms-")
                    .replace("-base.ko", ".txt"))
            paths += [profile["cga_base"], syms, *CGA_SHARED]
            if profile["id"] == "g264":
                paths += list(G264_LEGACY)
        else:
            paths += ["ksu6157/sigparam"]
            paths += [f"ksu6157-m6/{name}" for name in sorted(m6["files"])]
            if profile["id"] == "g7d":
                paths += ["g264/syms-g7d.txt"]
        if len(paths) != len(set(paths)):
            raise ValueError(f"duplicate path in {pid}")
        for name in paths:
            rows.append((pid, name, digest(ASSETS / name)))
        counts[pid] = len(paths)
    text = (
        "# MagicRoot 6.1.x deployed-asset integrity; generated by tools/gen_6157_integrity.py\n"
        "# profile<TAB>asset-relative-path<TAB>sha256\n"
        + "".join(f"{pid}\t{name}\t{sha}\n" for pid, name, sha in rows)
    )
    return text, counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting stale output")
    args = parser.parse_args()
    text, counts = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"FAIL stale or missing {OUTPUT.relative_to(ROOT)}")
        print("PASS 6157 integrity manifest current")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"WROTE {OUTPUT.relative_to(ROOT)}")
    print("profiles=" + ",".join(f"{k}:{v}" for k, v in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
