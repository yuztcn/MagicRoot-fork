#!/usr/bin/env python3
"""Install the BakaSU 4.2.0-rc3 asset set into the MagicRoot main project.

Sources (user-provided artifacts, cross-checked against BakaSU nightly):
  refs/upstream/bakasu/lkm/6.12/android16-6.12_kernelsu.ko
  refs/upstream/bakasu/BakaSU-ksud-aarch64.zip  (aarch64-linux-android/release/ksud)
  refs/upstream/bakasu/Manager-release.zip     (BakaSU_v4.2.0-rc3_35252-arm64-v8a-release.apk)

Outputs (main/app/assets):
  ksu-template-bakasu.ko
  ksud_bakasu
  BakaSU-manager.apk
  ksu_flavor

Also writes docs/reference/bakasu-asset-manifest.md.
"""
from __future__ import annotations

import hashlib
import zipfile
from pathlib import Path

WS = Path(__file__).resolve().parent.parent
UP = WS / "refs" / "upstream" / "bakasu"
ASSETS = WS / "main" / "app" / "assets"
DOCS = WS / "docs" / "reference"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def main() -> int:
    ASSETS.mkdir(parents=True, exist_ok=True)
    DOCS.mkdir(parents=True, exist_ok=True)
    rows = []

    # 1. LKM template (raw BakaSU nightly build; patched on device by ko_patch).
    lkm_src = UP / "lkm" / "6.12" / "android16-6.12_kernelsu.ko"
    lkm_dst = ASSETS / "ksu-template-bakasu.ko"
    data = lkm_src.read_bytes()
    lkm_dst.write_bytes(data)
    rows.append(("ksu-template-bakasu.ko", len(data), sha256_bytes(data), str(lkm_src)))

    # 2. ksud userspace matching the 4.2.0-rc3 manager/LKM.
    ksud_zip = UP / "BakaSU-ksud-aarch64.zip"
    with zipfile.ZipFile(ksud_zip) as z:
        ksud_data = z.read("aarch64-linux-android/release/ksud")
    ksud_dst = ASSETS / "ksud_bakasu"
    ksud_dst.write_bytes(ksud_data)
    rows.append(("ksud_bakasu", len(ksud_data), sha256_bytes(ksud_data), str(ksud_zip)))

    # 3. Manager APK (arm64-v8a), matching 4.2.0-rc3 / versionCode 35252.
    mgr_zip = UP / "Manager-release.zip"
    with zipfile.ZipFile(mgr_zip) as z:
        mgr_name = next(n for n in z.namelist() if "arm64-v8a" in n)
        mgr_data = z.read(mgr_name)
    mgr_dst = ASSETS / "BakaSU-manager.apk"
    mgr_dst.write_bytes(mgr_data)
    rows.append(("BakaSU-manager.apk", len(mgr_data), sha256_bytes(mgr_data),
                 f"{mgr_zip}!{mgr_name}"))

    # 4. flavor marker.
    (ASSETS / "ksu_flavor").write_text("resukisu", encoding="ascii")
    rows.append(("ksu_flavor", len("resukisu"), sha256_bytes(b"resukisu"), "generated"))

    # 5. syms tables already generated by tools/gen_syms*.py.
    for name in ("syms_61258_bakasu.txt", "syms_6138_bakasu.txt",
                 "syms_66_bakasu.txt"):
        p = ASSETS / name
        if p.exists():
            rows.append((name, p.stat().st_size, sha256_file(p), "generated by gen_syms"))

    manifest = ["# BakaSU asset manifest (main project)", "",
                "BakaSU project: https://github.com/Baka-SU/BakaSU",
                "Consistent build set: v4.2.0-rc3 (manager versionCode 35252),",
                "ksud 4.2.0, LKM 4.2.0-rc3 builds for KMI android16-6.12 / android15-6.6.",
                "",
                "| asset | size | sha256 | source |", "|---|---:|---|---|"]
    for name, size, digest, src in rows:
        manifest.append(f"| `{name}` | {size} | `{digest}` | {src} |")
    (DOCS / "bakasu-asset-manifest.md").write_text("\n".join(manifest) + "\n",
                                                  encoding="utf-8")
    for name, size, digest, _ in rows:
        print(f"{digest[:16]}  {size:>10}  {name}")
    print("wrote", DOCS / "bakasu-asset-manifest.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
